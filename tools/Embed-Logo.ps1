param(
    [Parameter(Mandatory = $true)]
    [string]$SourcePath
)

$ErrorActionPreference = 'Stop'
$bytes = [System.IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $SourcePath).Path)
$signature = [byte[]](137, 80, 78, 71, 13, 10, 26, 10)
for ($i = 0; $i -lt $signature.Length; $i++) {
    if ($bytes.Length -le $i -or $bytes[$i] -ne $signature[$i]) {
        throw 'The logo must be a PNG file.'
    }
}

$header = [System.Text.StringBuilder]::new()
[void]$header.AppendLine('// Generated by tools/Embed-Logo.ps1 from the supplied XTATECH PNG.')
[void]$header.AppendLine('#pragma once')
[void]$header.AppendLine('#include <Arduino.h>')
[void]$header.AppendLine('static const uint8_t XTATECH_LOGO_PNG[] PROGMEM = {')
for ($offset = 0; $offset -lt $bytes.Length; $offset += 16) {
    $end = [Math]::Min($offset + 15, $bytes.Length - 1)
    $row = ($bytes[$offset..$end] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
    [void]$header.AppendLine("  $row,")
}
[void]$header.AppendLine('};')
$destination = Join-Path (Split-Path $PSScriptRoot -Parent) 'ONT_Watchdog\XtatechLogo.h'
[System.IO.File]::WriteAllText($destination, $header.ToString(), [System.Text.Encoding]::ASCII)
Write-Output "Embedded $($bytes.Length) PNG bytes in $destination"
