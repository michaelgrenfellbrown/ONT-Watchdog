param(
    [Parameter(Mandatory = $true)]
    [string]$SourcePath
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$source = [System.Drawing.Image]::FromFile((Resolve-Path -LiteralPath $SourcePath).Path)
$width = 56
$height = 44
$bitmap = [System.Drawing.Bitmap]::new($width, $height)
$graphics = [System.Drawing.Graphics]::FromImage($bitmap)
$attributes = [System.Drawing.Imaging.ImageAttributes]::new()

function ConvertTo-Rgb565([int]$Red, [int]$Green, [int]$Blue) {
    return (($Red -shr 3) -shl 11) -bor (($Green -shr 2) -shl 5) -bor ($Blue -shr 3)
}

if ((ConvertTo-Rgb565 255 0 0) -ne 0xF800 -or
    (ConvertTo-Rgb565 0 255 0) -ne 0x07E0 -or
    (ConvertTo-Rgb565 0 0 255) -ne 0x001F -or
    (ConvertTo-Rgb565 255 255 255) -ne 0xFFFF) {
    throw 'RGB565 conversion failed its colour checks.'
}
try {
    $graphics.Clear([System.Drawing.Color]::Black)
    $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $attributes.SetColorKey([System.Drawing.Color]::FromArgb(240, 240, 240), [System.Drawing.Color]::White)
    $rectangle = [System.Drawing.Rectangle]::new(0, 0, $width, $height)
    $graphics.DrawImage($source, $rectangle, 0, 0, $source.Width, $source.Height,
        [System.Drawing.GraphicsUnit]::Pixel, $attributes)
    $header = [System.Text.StringBuilder]::new()
    [void]$header.AppendLine('// Generated by tools/Embed-TftLogo.ps1 from the supplied XTATECH PNG.')
    [void]$header.AppendLine('#pragma once')
    [void]$header.AppendLine('#include <Arduino.h>')
    [void]$header.AppendLine("constexpr uint8_t TFT_LOGO_WIDTH = $width;")
    [void]$header.AppendLine("constexpr uint8_t TFT_LOGO_HEIGHT = $height;")
    [void]$header.AppendLine('static const uint16_t XTATECH_TFT_LOGO[] PROGMEM = {')
    for ($y = 0; $y -lt $height; $y++) {
        $row = for ($x = 0; $x -lt $width; $x++) {
            $pixel = $bitmap.GetPixel($x, $y)
            $rgb565 = ConvertTo-Rgb565 $pixel.R $pixel.G $pixel.B
            '0x{0:X4}' -f $rgb565
        }
        [void]$header.AppendLine(('  ' + ($row -join ', ') + ','))
    }
    [void]$header.AppendLine('};')
    $destination = Join-Path (Split-Path $PSScriptRoot -Parent) 'ONT_Watchdog_ESP8266\XtatechTftLogo.h'
    [System.IO.File]::WriteAllText($destination, $header.ToString(), [System.Text.Encoding]::ASCII)
    Write-Output "Embedded ${width}x${height} RGB565 TFT logo with black background in $destination"
} finally {
    $attributes.Dispose()
    $graphics.Dispose()
    $bitmap.Dispose()
    $source.Dispose()
}
